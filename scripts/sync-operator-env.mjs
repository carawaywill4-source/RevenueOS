#!/usr/bin/env node
/**
 * Create services/operator/.env from .env.portfolio for Mac Core boot.
 * Does not overwrite an existing .env unless --force is passed.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const src = path.join(ROOT, ".env.portfolio");
const dest = path.join(ROOT, "services/operator/.env");
const force = process.argv.includes("--force");

if (!existsSync(src)) {
  console.error("Missing .env.portfolio");
  process.exit(1);
}
if (existsSync(dest) && !force) {
  console.log("services/operator/.env already exists (use --force to overwrite)");
  process.exit(0);
}

function parse(file) {
  const out = {};
  for (const line of readFileSync(file, "utf8").split("\n")) {
    const s = line.trim();
    if (!s || s.startsWith("#") || !s.includes("=")) continue;
    const i = s.indexOf("=");
    out[s.slice(0, i).trim()] = s.slice(i + 1).trim();
  }
  return out;
}

const env = parse(src);
const keys = [
  "SUPABASE_URL",
  "SUPABASE_SERVICE_ROLE_KEY",
  "OPENAI_API_KEY",
  "OPENAI_MODEL",
  "RESEND_API_KEY",
  "STRIPE_SECRET_KEY",
  "SIDECAR_URL",
  "SIDECAR_TOKEN",
];

const lines = [
  "# Generated by scripts/sync-operator-env.mjs — do not commit",
  "OPERATOR_NAME=mac-revenueos-core",
  "PORT=8080",
  "SHADOW_MODE=1",
  "CLAIM_ENABLED=0",
  "BUSINESSES=raiseready",
  "MAX_CONCURRENCY=1",
  "PER_BUSINESS_MIN_INTERVAL_MS=60000",
  "TICK_BUDGET_MS=120000",
  "MAX_JOBS_PER_TICK=8",
  "CLAIM_LEASE_MS=300000",
  "SIDECAR_DRY_RUN=1",
];
for (const k of keys) {
  if (env[k]) lines.push(`${k}=${env[k]}`);
}
writeFileSync(dest, lines.join("\n") + "\n", { mode: 0o600 });
console.log("Wrote", dest, `(SHADOW_MODE=1 CLAIM_ENABLED=0 BUSINESSES=raiseready)`);
