#!/usr/bin/env node
/**
 * Create services/operator/.env by reusing existing local RevenueOS Supabase
 * credentials — never invent a second project.
 *
 * Source priority for SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY:
 *   1. .env.local (TributeReady / live durable memory — verified)
 *   2. apps/raiseready/.env.local (portfolio app donor)
 *   3. .env.portfolio (shared sync file; may omit Supabase)
 *
 * Does not print secret values. Does not commit.
 *
 *   node scripts/sync-operator-env.mjs [--force]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const dest = path.join(ROOT, "services/operator/.env");
const force = process.argv.includes("--force");

function parse(file) {
  const out = {};
  if (!existsSync(file)) return out;
  for (const line of readFileSync(file, "utf8").split("\n")) {
    const s = line.trim();
    if (!s || s.startsWith("#") || !s.includes("=")) continue;
    const i = s.indexOf("=");
    let v = s.slice(i + 1).trim();
    if (
      (v.startsWith('"') && v.endsWith('"')) ||
      (v.startsWith("'") && v.endsWith("'"))
    ) {
      v = v.slice(1, -1);
    }
    out[s.slice(0, i).trim()] = v;
  }
  return out;
}

function projectRef(url) {
  try {
    return new URL(url).hostname.split(".")[0];
  } catch {
    return null;
  }
}

const sources = [
  { file: path.join(ROOT, ".env.local"), label: ".env.local" },
  {
    file: path.join(ROOT, "apps/raiseready/.env.local"),
    label: "apps/raiseready/.env.local",
  },
  { file: path.join(ROOT, ".env.portfolio"), label: ".env.portfolio" },
];

const merged = {};
const provenance = {};
for (const { file, label } of sources) {
  const env = parse(file);
  for (const [k, v] of Object.entries(env)) {
    if (!v || String(v).startsWith("[SENSI")) continue;
    if (merged[k] === undefined) {
      merged[k] = v;
      provenance[k] = label;
    }
  }
}

const url = merged.SUPABASE_URL;
const key = merged.SUPABASE_SERVICE_ROLE_KEY;
if (!url || !key) {
  console.error(
    "Could not find SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY in local env files.",
  );
  console.error(
    "Checked: .env.local, apps/raiseready/.env.local, .env.portfolio",
  );
  process.exit(1);
}

if (existsSync(dest) && !force) {
  const existing = parse(dest);
  if (existing.SUPABASE_URL && existing.SUPABASE_SERVICE_ROLE_KEY) {
    console.log(
      "services/operator/.env already has Supabase keys (use --force to rewrite)",
    );
    console.log(
      JSON.stringify({
        operatorProjectRef: projectRef(existing.SUPABASE_URL),
        sourceWouldBe: provenance.SUPABASE_URL,
        sourceProjectRef: projectRef(url),
      }),
    );
    process.exit(0);
  }
}

const copyKeys = [
  "SUPABASE_URL",
  "SUPABASE_SERVICE_ROLE_KEY",
  "OPENAI_API_KEY",
  "OPENAI_MODEL",
  "RESEND_API_KEY",
  "STRIPE_SECRET_KEY",
  "SIDECAR_URL",
  "SIDECAR_TOKEN",
  "CRON_SECRET",
  "PORTFOLIO_PULSE_TOKEN",
  "GUMROAD_ACCESS_TOKEN",
  "GUMROAD_APPLICATION_ID",
  "GUMROAD_APPLICATION_SECRET",
  "GUMROAD_SELLER_ID",
  "YOUTUBE_API_KEY",
  "GOOGLE_SERVICE_ACCOUNT_JSON",
  "PRODUCTHUNT_DEVELOPER_TOKEN",
  "REVENUEOS_ATTRIBUTION_SECRET",
];

const lines = [
  "# Generated by scripts/sync-operator-env.mjs — gitignored — do not commit",
  `# Supabase sourced from ${provenance.SUPABASE_URL} (ref ${projectRef(url)})`,
  "OPERATOR_NAME=mac-revenueos-core",
  "PORT=8080",
  "SHADOW_MODE=1",
  "CLAIM_ENABLED=0",
  "BUSINESSES=raiseready",
  "MAX_CONCURRENCY=1",
  "PER_BUSINESS_MIN_INTERVAL_MS=60000",
  "TICK_BUDGET_MS=120000",
  "MAX_JOBS_PER_TICK=8",
  "CLAIM_LEASE_MS=300000",
  "SIDECAR_DRY_RUN=1",
];
for (const k of copyKeys) {
  if (merged[k]) lines.push(`${k}=${merged[k]}`);
}
writeFileSync(dest, lines.join("\n") + "\n", { mode: 0o600 });
console.log(
  JSON.stringify(
    {
      wrote: "services/operator/.env",
      projectRef: projectRef(url),
      supabaseSource: provenance.SUPABASE_URL,
      shadowMode: 1,
      claimEnabled: 0,
      businesses: "raiseready",
      hasServiceRole: true,
      hasDatabaseUrl: Boolean(merged.DATABASE_URL || merged.POSTGRES_URL),
      hasAccessToken: Boolean(merged.SUPABASE_ACCESS_TOKEN),
    },
    null,
    2,
  ),
);
